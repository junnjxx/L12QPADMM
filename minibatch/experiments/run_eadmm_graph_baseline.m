function result = run_eadmm_graph_baseline(problem,cfg)
%RUN_EADMM_GRAPH_BASELINE
% Wiegele-Zhao eADMM directly on an official graph instance.
%
% Graph model:
%
%   min 0.5*<L,X>
%
% and, for the current graph problem,
%
%   J_common = 0.5*<L,X>.
%
% Therefore there is NO batching->graph affine conversion here.
%
% Runtime convention:
%
%   raw time
%       = base DNN solve + all Vc rounding restarts
%
%   post time
%       = ONE common 2-opt call applied to the best raw Vc solution
%
% MET and safe-LB postprocessing are certification overhead and are
% excluded from the solution-generation runtime.

    if ~isfield(problem,'type') || ...
            string(problem.type) ~= "graph"

        error( ...
            'run_eadmm_graph_baseline requires problem.type="graph".');
    end

    N = ...
        problem.num_samples;

    B = ...
        problem.num_batches;

    bs = ...
        problem.batch_size;

    W = ...
        problem.W;

    %% ============================================================
    % Direct graph model
    % ============================================================

    [A_sdp,b_sdp,C_sdp] = ...
        kequi_form( ...
            W, ...
            int16(B));

    %% ============================================================
    % Objective consistency
    % ============================================================

    Pcheck = zeros(N,B);

    for jj=1:B

        idx = ...
            (jj-1)*bs+(1:bs);

        Pcheck(idx,jj)=1;
    end

    Hcheck = ...
        Pcheck*Pcheck';

    J_project = ...
        evaluate_partition( ...
            Pcheck, ...
            problem, ...
            cfg.matrix.eta);

    J_eadmm = ...
        sum(C_sdp.*Hcheck,'all');

    err = ...
        abs( ...
            J_eadmm ...
            - ...
            J_project.common_objective);

    tol = ...
        1e-9*max( ...
            [1, ...
             abs(J_eadmm), ...
             abs(J_project.common_objective)]);

    if err > tol

        error( ...
            ['eADMM graph objective mismatch: ', ...
             'J_eadmm=%.12e, J_common=%.12e.'], ...
            J_eadmm, ...
            J_project.common_objective);
    end

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('eADMM graph baseline\n');
    fprintf('n=%d | k=%d | bs=%d\n',N,B,bs);
    fprintf('Direct official adjacency W -> kequi_form(W,k)\n');
    fprintf('No W=1-Phi conversion is used.\n');
    fprintf('============================================================\n');

    %% ============================================================
    % Base DNN
    % ============================================================

    tdnn = tic;

    switch string(cfg.eadmm.init_mode)

        case "zero"

            [ ...
                X_dnn, ...
                y_dnn, ...
                Z_dnn, ...
                S_dnn, ...
                ~,~, ...
                sigma_dnn_final, ...
                ~,~, ...
                dnn_iterations ...
            ] = ...
                aadmm_3b( ...
                    A_sdp, ...
                    b_sdp, ...
                    C_sdp, ...
                    cfg.eadmm.max_iter, ...
                    cfg.eadmm.sigma0, ...
                    cfg.eadmm.tol);

        case "uniform"

            rho0 = ...
                (bs-1)/(N-1);

            H0 = ...
                rho0*ones(N,N) ...
                + ...
                (1-rho0)*eye(N);

            normA0 = ...
                full( ...
                    min( ...
                        1e12, ...
                        max(1,norm(A_sdp,'fro'))));

            normb0 = ...
                max(1,norm(b_sdp));

            Y0 = ...
                H0*normA0/normb0;

            Z0 = ...
                zeros(N,N);

            S0 = ...
                zeros(N,N);

            [ ...
                X_dnn, ...
                y_dnn, ...
                Z_dnn, ...
                S_dnn, ...
                ~,~, ...
                sigma_dnn_final, ...
                ~,~, ...
                dnn_iterations ...
            ] = ...
                aadmm_3b( ...
                    A_sdp, ...
                    b_sdp, ...
                    C_sdp, ...
                    cfg.eadmm.max_iter, ...
                    cfg.eadmm.sigma0, ...
                    cfg.eadmm.tol, ...
                    Y0,Z0,S0);

        otherwise

            error( ...
                'Unknown cfg.eadmm.init_mode: %s.', ...
                string(cfg.eadmm.init_mode));
    end

    dnn_solve_time = ...
        toc(tdnn);

    dnn_avg_iter_time = ...
        dnn_solve_time ...
        / ...
        max(dnn_iterations,1);

    %% ============================================================
    % DNN diagnostics
    % ============================================================

    if size(A_sdp,1)==numel(X_dnn)

        Aop = ...
            A_sdp';

    else

        Aop = ...
            A_sdp;
    end

    dnn_primal_eq_rel = ...
        norm( ...
            Aop*X_dnn(:)-b_sdp) ...
        /(1+norm(b_sdp));

    Aty_dnn = ...
        reshape( ...
            Aop'*y_dnn, ...
            N,N);

    dnn_dual_res_mat = ...
        C_sdp ...
        - ...
        Aty_dnn ...
        - ...
        Z_dnn ...
        - ...
        S_dnn;

    dnn_dual_eq_rel = ...
        norm(dnn_dual_res_mat,'fro') ...
        /(1+norm(C_sdp,'fro'));

    Xsym = ...
        0.5*(X_dnn+X_dnn');

    dnn_min_eig_X = ...
        min(eig(full(Xsym)));

    dnn_nonneg_violation = ...
        norm(min(X_dnn,0),'fro') ...
        /(1+norm(X_dnn,'fro'));

    dnn_sdp_jcommon_score = ...
        sum( ...
            problem.Phi.*X_dnn, ...
            'all') ...
        /(2*bs^2);

    fprintf('\n');
    fprintf('[eADMM DNN]\n');
    fprintf('iterations=%d\n',dnn_iterations);
    fprintf('solve time=%.6f sec\n',dnn_solve_time);
    fprintf('sec/iter=%.6e\n',dnn_avg_iter_time);
    fprintf('relaxed J_common=%.10e\n', ...
        dnn_sdp_jcommon_score);

    %% ============================================================
    % MET strengthening
    % ============================================================

    met_time = 0;
    met_separation_time = 0;
    met_solve_time = 0;

    met_rounds = 0;
    met_separation_calls = 0;
    met_num_constraints = 0;

    met_terminated_no_violation = false;
    met_hit_round_limit = false;

    met_records = struct([]);

    X_met = X_dnn;
    y_met = [];
    ybar_met = [];
    Z_met = Z_dnn;
    S_met = S_dnn;
    s_met = [];
    v_met = [];

    sigma_met_final = NaN;

    B_met = ...
        sparse(0,N*N);

    f_met = ...
        zeros(0,1);

    T_met = ...
        zeros(0,4);

    hash_met = ...
        zeros(0,1);

    if cfg.eadmm.met.enabled

        if N>1000

            error( ...
                'Upstream ADMM-GP MET hash convention supports n<=1000.');
        end

        L_box = ...
            zeros(N,N);

        U_box = ...
            Inf(N,N);

        tmet = tic;

        while met_rounds < cfg.eadmm.met.max_rounds

            old_num = ...
                numel(f_met);

            met_separation_calls = ...
                met_separation_calls+1;

            tsep = tic;

            [ ...
                f_candidate, ...
                T_candidate, ...
                hash_candidate, ...
                g_new, ...
                brk ...
            ] = ...
                separation_kequi( ...
                    X_met, ...
                    f_met, ...
                    T_met, ...
                    hash_met, ...
                    cfg.eadmm.met.max_ineq_per_round, ...
                    cfg.eadmm.met.violation_tol);

            sep_elapsed = ...
                toc(tsep);

            met_separation_time = ...
                met_separation_time ...
                + ...
                sep_elapsed;

            new_num = ...
                numel(f_candidate);

            added = ...
                new_num-old_num;

            if added<=0

                met_terminated_no_violation = true;

                break;
            end

            f_met = ...
                f_candidate;

            T_met = ...
                T_candidate;

            hash_met = ...
                hash_candidate;

            [B_met,f_met] = ...
                formtri_kc( ...
                    T_met, ...
                    f_met, ...
                    N);

            met_rounds = ...
                met_rounds+1;

            tsolve = tic;

            [ ...
                X_met, ...
                y_met, ...
                ybar_met, ...
                Z_met, ...
                S_met, ...
                s_met, ...
                v_met, ...
                sigma_met_final, ...
                iter_met ...
            ] = ...
                mprw_ineq_general( ...
                    A_sdp, ...
                    B_met, ...
                    b_sdp, ...
                    C_sdp, ...
                    f_met, ...
                    L_box, ...
                    U_box, ...
                    cfg.eadmm.max_iter, ...
                    cfg.eadmm.met.sigma0, ...
                    cfg.eadmm.tol);

            solve_elapsed = ...
                toc(tsolve);

            met_solve_time = ...
                met_solve_time ...
                + ...
                solve_elapsed;

            BX = ...
                B_met*X_met(:);

            met_violation_rel = ...
                norm(max(f_met-BX,0)) ...
                /(1+norm(f_met));

            met_records(met_rounds).round = ...
                met_rounds;

            met_records(met_rounds).added = ...
                added;

            met_records(met_rounds).total = ...
                numel(f_met);

            met_records(met_rounds).max_new_violation = ...
                max(g_new);

            met_records(met_rounds).ineq_violation_rel = ...
                met_violation_rel;

            met_records(met_rounds).iterations = ...
                iter_met;

            met_records(met_rounds).solve_time = ...
                solve_elapsed;

            met_records(met_rounds).separation_time = ...
                sep_elapsed;

            if brk

                met_terminated_no_violation = true;

                break;
            end
        end

        met_time = ...
            toc(tmet);

        met_num_constraints = ...
            numel(f_met);

        if ...
                met_rounds>=cfg.eadmm.met.max_rounds ...
                && ...
                ~met_terminated_no_violation

            met_hit_round_limit = true;
        end
    end

    if met_num_constraints>0

        met_sdp_jcommon_score = ...
            sum( ...
                problem.Phi.*X_met, ...
                'all') ...
            /(2*bs^2);

        met_primal_eq_rel = ...
            norm( ...
                Aop*X_met(:)-b_sdp) ...
            /(1+norm(b_sdp));

        met_ineq_violation_rel = ...
            norm( ...
                max( ...
                    f_met-B_met*X_met(:), ...
                    0)) ...
            /(1+norm(f_met));

        Aty_met = ...
            reshape( ...
                Aop'*y_met, ...
                N,N);

        Bty_met = ...
            reshape( ...
                B_met'*ybar_met, ...
                N,N);

        met_dual_eq_rel = ...
            norm( ...
                C_sdp ...
                - ...
                Aty_met ...
                - ...
                Bty_met ...
                - ...
                Z_met ...
                - ...
                S_met, ...
                'fro') ...
            /(1+norm(C_sdp,'fro'));

    else

        met_sdp_jcommon_score = NaN;
        met_primal_eq_rel = NaN;
        met_ineq_violation_rel = NaN;
        met_dual_eq_rel = NaN;
    end

    %% ============================================================
    % Safe lower bound
    %
    % Existing helper converts as
    %
    %   (LB_graph-offset)/scale.
    %
    % Here graph scale IS J_common scale, so use
    %
    %   scale=1, offset=0.
    %
    % This is implemented by passing batch_size=1 and constant=0.
    % ============================================================

    safe_lb = struct();

    safe_lb.common = NaN;
    safe_lb.graph_internal = NaN;
    safe_lb.y = [];
    safe_lb.ybar = [];
    safe_lb.time = 0;

    safe_lb.min_eig_Zplus = NaN;
    safe_lb.min_S = NaN;
    safe_lb.min_ybar = NaN;
    safe_lb.dual_identity_rel = NaN;

    safe_lb.numerically_feasible = false;
    safe_lb.source = "none";

    if cfg.eadmm.compute_safe_lower_bound

        if met_num_constraints>0

            safe_lb = ...
                compute_safe_lower_bound_met( ...
                    A_sdp, ...
                    B_met, ...
                    b_sdp, ...
                    f_met, ...
                    C_sdp, ...
                    Z_met, ...
                    S_met, ...
                    1, ...
                    0);

            safe_lb.source = ...
                "DNN+MET/post_proc_3";

        else

            safe_lb = ...
                compute_safe_lower_bound( ...
                    A_sdp, ...
                    b_sdp, ...
                    C_sdp, ...
                    Z_dnn, ...
                    S_dnn, ...
                    1, ...
                    0);

            safe_lb.ybar = [];
            safe_lb.min_ybar = NaN;

            safe_lb.source = ...
                "DNN/post_proc_2";
        end
    end

    %% ============================================================
    % Vc rounding
    % ============================================================

    R = ...
        cfg.eadmm.rounding_restarts;

    checkpoints = ...
        unique( ...
            round( ...
                cfg.eadmm.rounding_checkpoints(:)'));

    checkpoints = ...
        checkpoints( ...
            checkpoints>=1 ...
            & ...
            checkpoints<=R);

    if isempty(checkpoints) || ...
            checkpoints(end)~=R

        checkpoints = ...
            unique([checkpoints,R]);
    end

    vc_jcommon = ...
        nan(R,1);

    vc2_jcommon = ...
        nan(R,1);

    vc_best_jcommon_history = ...
        nan(R,1);

    vc2_best_jcommon_history = ...
        nan(R,1);

    cumulative_vc_time = ...
        nan(R,1);

    cumulative_2opt_time = ...
        zeros(R,1);

    rounding_seed = ...
        nan(R,1);

    two_opt_seed = ...
        nan(R,1);

    best_vc_jcommon = inf;
    best_vc_restart = NaN;
    best_vc_I = [];
    best_vc_metrics = struct();

    vc_time_total = 0;

    checkpoint_records = struct([]);
    cp_id = 0;

    for rr=1:R

        seed_rr = ...
            cfg.seed.eadmm_rounding_base ...
            + ...
            rr-1;

        rounding_seed(rr) = ...
            seed_rr;

        tr = tic;

        [~,~,~,part_cell] = ...
            kequi_rounding( ...
                seed_rr, ...
                X_dnn, ...
                double(B), ...
                C_sdp);

        vc_time_total = ...
            vc_time_total ...
            + ...
            toc(tr);

        I_rr = ...
            part_cell_to_I_graph( ...
                part_cell, ...
                bs,B,N);

        P_rr = ...
            batches_to_assignment( ...
                I_rr,N,B,bs);

        metrics_rr = ...
            evaluate_partition( ...
                P_rr, ...
                problem, ...
                cfg.matrix.eta);

        vc_jcommon(rr) = ...
            metrics_rr.common_objective;

        if vc_jcommon(rr)<best_vc_jcommon

            best_vc_jcommon = ...
                vc_jcommon(rr);

            best_vc_restart = ...
                rr;

            best_vc_I = ...
                I_rr;

            best_vc_metrics = ...
                metrics_rr;
        end

        vc_best_jcommon_history(rr) = ...
            best_vc_jcommon;

        cumulative_vc_time(rr) = ...
            vc_time_total;

        if any(rr==checkpoints)

            cp_id = ...
                cp_id+1;

            checkpoint_records(cp_id).restart = ...
                rr;

            checkpoint_records(cp_id).vc_best_jcommon = ...
                best_vc_jcommon;

            checkpoint_records(cp_id).vc2_best_jcommon = ...
                NaN;

            checkpoint_records(cp_id).vc_time = ...
                vc_time_total;

            checkpoint_records(cp_id).two_opt_time = ...
                0;
        end
    end

    %% ============================================================
    % ONE common 2-opt on the best raw Vc result
    % ============================================================

    two_opt_time_total = 0;

    best_vc2_jcommon = NaN;
    best_vc2_restart = NaN;
    best_vc2_I = [];
    best_vc2_metrics = struct();

    if cfg.eadmm.use_2opt

        opt2 = struct();

        opt2.seed = ...
            cfg.seed.two_opt_base;

        opt2.cost_tol = ...
            cfg.two_opt.cost_tol;

        opt2.verbose = ...
            cfg.eadmm.verbose_2opt;

        opt2.eta = ...
            cfg.matrix.eta;

        post = ...
            apply_common_two_opt( ...
                best_vc_I, ...
                problem, ...
                opt2);

        two_opt_time_total = ...
            post.time;

        best_vc2_jcommon = ...
            post.metrics_after.common_objective;

        best_vc2_restart = ...
            best_vc_restart;

        best_vc2_I = ...
            post.I_after;

        best_vc2_metrics = ...
            post.metrics_after;

        vc2_jcommon(best_vc_restart) = ...
            best_vc2_jcommon;

        vc2_best_jcommon_history(R) = ...
            best_vc2_jcommon;

        cumulative_2opt_time(R) = ...
            two_opt_time_total;

        two_opt_seed(best_vc_restart) = ...
            cfg.seed.two_opt_base;

        if ~isempty(checkpoint_records)

            q = ...
                find( ...
                    [checkpoint_records.restart]==R, ...
                    1, ...
                    'last');

            if ~isempty(q)

                checkpoint_records(q).vc2_best_jcommon = ...
                    best_vc2_jcommon;

                checkpoint_records(q).two_opt_time = ...
                    two_opt_time_total;
            end
        end
    end

    %% ============================================================
    % Final chosen solution
    % ============================================================

    if cfg.eadmm.use_2opt

        chosen_I = ...
            best_vc2_I;

        chosen_metrics = ...
            best_vc2_metrics;

        chosen_label = ...
            "best raw Vc + common2opt";

        chosen_restart = ...
            best_vc_restart;

    else

        chosen_I = ...
            best_vc_I;

        chosen_metrics = ...
            best_vc_metrics;

        chosen_label = ...
            "Vc";

        chosen_restart = ...
            best_vc_restart;
    end

    %% ============================================================
    % Result
    % ============================================================

    result = struct();

    result.method = ...
        "eADMM-SDP-graph";

    result.I = ...
        chosen_I;

    result.P = ...
        batches_to_assignment( ...
            chosen_I,N,B,bs);

    result.metrics = ...
        chosen_metrics;

    result.chosen_label = ...
        chosen_label;

    result.chosen_restart = ...
        chosen_restart;

    % Base DNN
    result.A_sdp = A_sdp;
    result.b_sdp = b_sdp;
    result.C_sdp = C_sdp;

    result.X_sdp = X_dnn;
    result.y_sdp = y_dnn;
    result.Z_sdp = Z_dnn;
    result.S_sdp = S_dnn;

    result.sigma_final = ...
        sigma_dnn_final;

    result.init_mode = ...
        string(cfg.eadmm.init_mode);

    result.dnn_iterations = ...
        dnn_iterations;

    result.dnn_avg_iter_time = ...
        dnn_avg_iter_time;

    result.primal_eq_rel = ...
        dnn_primal_eq_rel;

    result.dual_eq_rel = ...
        dnn_dual_eq_rel;

    result.min_eig_X = ...
        dnn_min_eig_X;

    result.nonneg_violation = ...
        dnn_nonneg_violation;

    result.sdp_jcommon_score = ...
        dnn_sdp_jcommon_score;

    % MET
    result.met_enabled = ...
        cfg.eadmm.met.enabled;

    result.met_rounds = ...
        met_rounds;

    result.met_separation_calls = ...
        met_separation_calls;

    result.met_num_constraints = ...
        met_num_constraints;

    result.met_time = ...
        met_time;

    result.met_separation_time = ...
        met_separation_time;

    result.met_solve_time = ...
        met_solve_time;

    result.met_terminated_no_violation = ...
        met_terminated_no_violation;

    result.met_hit_round_limit = ...
        met_hit_round_limit;

    result.met_records = ...
        met_records;

    result.B_met = B_met;
    result.f_met = f_met;
    result.T_met = T_met;

    result.X_met = X_met;
    result.y_met = y_met;
    result.ybar_met = ybar_met;
    result.Z_met = Z_met;
    result.S_met = S_met;
    result.s_met = s_met;
    result.v_met = v_met;

    result.sigma_met_final = ...
        sigma_met_final;

    result.met_sdp_jcommon_score = ...
        met_sdp_jcommon_score;

    result.met_primal_eq_rel = ...
        met_primal_eq_rel;

    result.met_ineq_violation_rel = ...
        met_ineq_violation_rel;

    result.met_dual_eq_rel = ...
        met_dual_eq_rel;

    % Safe LB
    result.safe_jcommon_lower_bound = ...
        safe_lb.common;

    result.safe_graph_lower_bound_internal = ...
        safe_lb.graph_internal;

    % Graph problem uses exactly the same scale.
    result.graph_to_jcommon_constant = ...
        0;

    result.safe_lower_bound_source = ...
        safe_lb.source;

    result.safe_lower_bound_y = ...
        safe_lb.y;

    result.safe_lower_bound_ybar = ...
        safe_lb.ybar;

    result.safe_lower_bound_postprocess_time = ...
        safe_lb.time;

    result.certification_met_time = ...
        met_time;

    result.certification_additional_time = ...
        met_time ...
        + ...
        safe_lb.time;

    result.safe_lower_bound_time = ...
        result.certification_additional_time;

    result.safe_lower_bound_min_eig_Z = ...
        safe_lb.min_eig_Zplus;

    slack_checks = ...
        [safe_lb.min_S,safe_lb.min_ybar];

    slack_checks = ...
        slack_checks(isfinite(slack_checks));

    if isempty(slack_checks)

        result.safe_lower_bound_min_slack = ...
            NaN;

    else

        result.safe_lower_bound_min_slack = ...
            min(slack_checks);
    end

    result.safe_lower_bound_dual_identity_rel = ...
        safe_lb.dual_identity_rel;

    result.safe_lower_bound_numerically_feasible = ...
        safe_lb.numerically_feasible;

    % Rounding
    result.vc_jcommon = ...
        vc_jcommon;

    result.vc2_jcommon = ...
        vc2_jcommon;

    result.vc_best_jcommon_history = ...
        vc_best_jcommon_history;

    result.vc2_best_jcommon_history = ...
        vc2_best_jcommon_history;

    result.best_vc_jcommon = ...
        best_vc_jcommon;

    result.best_vc_restart = ...
        best_vc_restart;

    result.best_vc_I = ...
        best_vc_I;

    result.best_vc_metrics = ...
        best_vc_metrics;

    result.best_vc2_jcommon = ...
        best_vc2_jcommon;

    result.best_vc2_restart = ...
        best_vc2_restart;

    result.best_vc2_I = ...
        best_vc2_I;

    result.best_vc2_metrics = ...
        best_vc2_metrics;

    result.cumulative_vc_time = ...
        cumulative_vc_time;

    result.cumulative_2opt_time = ...
        cumulative_2opt_time;

    result.rounding_seed = ...
        rounding_seed;

    result.two_opt_seed = ...
        two_opt_seed;

    result.checkpoints = ...
        checkpoint_records;

    %% ============================================================
    % Fair timing
    % ============================================================

    result.solve_time = ...
        dnn_solve_time;

    result.vc_time = ...
        vc_time_total;

    result.two_opt_time = ...
        two_opt_time_total;

    result.solution_time_raw = ...
        dnn_solve_time ...
        + ...
        vc_time_total;

    result.solution_time_with_2opt = ...
        result.solution_time_raw ...
        + ...
        two_opt_time_total;

    if cfg.eadmm.use_2opt

        result.total_time = ...
            result.solution_time_with_2opt;

    else

        result.total_time = ...
            result.solution_time_raw;
    end

    result.certification_from_scratch_time = ...
        dnn_solve_time ...
        + ...
        result.certification_additional_time;

    result.total_time_with_certification = ...
        result.total_time ...
        + ...
        result.certification_additional_time;

    %% ============================================================
    % Summary
    % ============================================================

    fprintf('\n');
    fprintf('==================== eADMM graph summary ====================\n');
    fprintf('*raw J_common = %.10e* | restart=%d\n', ...
        best_vc_jcommon,best_vc_restart);
    fprintf('*raw generation time = %.6f sec*\n', ...
        result.solution_time_raw);

    if cfg.eadmm.use_2opt

        fprintf('*raw-best + common2opt J_common = %.10e*\n', ...
            best_vc2_jcommon);

        fprintf('common2opt time = %.6f sec\n', ...
            two_opt_time_total);

        fprintf('*total generation time = %.6f sec*\n', ...
            result.solution_time_with_2opt);
    end

    if cfg.eadmm.compute_safe_lower_bound

        fprintf('*safe J_common lower bound = %.10e*\n', ...
            result.safe_jcommon_lower_bound);

        fprintf('safe-LB source = %s\n', ...
            string(result.safe_lower_bound_source));
    end

    fprintf('============================================================\n');
end


function I = part_cell_to_I_graph(part_cell,bs,B,N)

    if numel(part_cell)~=B

        error( ...
            'Expected %d groups, got %d.', ...
            B,numel(part_cell));
    end

    I = ...
        zeros(bs,B);

    for j=1:B

        idx = ...
            part_cell{j};

        if numel(idx)~=bs

            error( ...
                'Rounded group %d has %d vertices; expected %d.', ...
                j,numel(idx),bs);
        end

        I(:,j) = ...
            idx(:);
    end

    flat = ...
        I(:);

    if numel(unique(flat))~=N || ...
            ~isequal(sort(flat),(1:N)')

        error( ...
            'eADMM rounding did not return a valid equipartition.');
    end
end