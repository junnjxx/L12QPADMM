%% RUN_GRAPH_EXPERIMENT
% Official ADMM-GP k-equipartition benchmark.
%
% Mathematical convention:
%
%   W = official adjacency
%   L = D-W
%   A_matrix = L
%   G_matrix = 0
%   Phi = bs^2*L
%
% Hence all methods are evaluated by
%
%   J_common(P)
%       = 0.5*<L,P*P'>.

clear;
close all;
clc;

project_root = ...
    fileparts(mfilename('fullpath'));

%% ============================================================
% Paths
% ============================================================

addpath(fullfile(project_root,'config'));
addpath(fullfile(project_root,'data'));
addpath(fullfile(project_root,'problem'));

addpath( ...
    genpath( ...
        fullfile(project_root,'methods')));

addpath(fullfile(project_root,'postprocess'));
addpath(fullfile(project_root,'experiments'));
addpath(fullfile(project_root,'reporting'));
addpath(fullfile(project_root,'utils'));

addpath( ...
    genpath( ...
        fullfile( ...
            project_root, ...
            'third_party', ...
            'ADMM-GP')));

%% ============================================================
% Config
% ============================================================

cfg = ...
    config_graph();

cfg.paths.project_root = ...
    project_root;

cfg.paths.third_party_admm_gp = ...
    fullfile( ...
        project_root, ...
        'third_party', ...
        'ADMM-GP');

if cfg.methods.enabled.eadmm && ...
        ~exist(cfg.paths.third_party_admm_gp,'dir')

    error( ...
        'ADMM-GP third-party directory not found: %s', ...
        cfg.paths.third_party_admm_gp);
end

%% ============================================================
% Log
% ============================================================

log_dir = ...
    fullfile( ...
        project_root, ...
        'logs');

if ~exist(log_dir,'dir')

    mkdir(log_dir);
end

timestamp = ...
    datestr(now,'yyyymmdd_HHMMSS');

log_name = ...
    sprintf( ...
        'graph_%s_N%d_k%d_%s.txt', ...
        char(cfg.graph.family), ...
        cfg.graph.n, ...
        cfg.graph.k, ...
        timestamp);

log_file = ...
    fullfile( ...
        log_dir, ...
        log_name);

diary off;
diary(log_file);

diary_cleanup = ...
    onCleanup(@() diary('off'));

%% ============================================================
% Load graph
% ============================================================

fprintf('\n');
fprintf('============================================================\n');
fprintf('Official ADMM-GP graph experiment\n');
fprintf('family=%s | n=%d | k=%d | bs=%d\n', ...
    cfg.graph.family, ...
    cfg.graph.n, ...
    cfg.graph.k, ...
    cfg.batch.size);

fprintf('methods=%s\n', ...
    strjoin(cfg.methods.run,' -> '));

fprintf('============================================================\n');

data = ...
    load_admm_gp_kequipartition( ...
        cfg, ...
        project_root);

%% ============================================================
% Shared problem
% ============================================================

problem = ...
    build_graph_partition_problem( ...
        data, ...
        cfg);

fprintf('\n');
fprintf('Unified objective:\n');
fprintf('  J_common(P) = 0.5*<L,P*P''>\n');
fprintf('Matrix uses A=L and G=0.\n');
fprintf('Lp uses A=L.\n');
fprintf('eADMM directly uses official adjacency W.\n');
fprintf('MMDLP/Vector use Phi=bs^2*L.\n');

%% ============================================================
% Run methods
% ============================================================

results = struct();

run_methods = ...
    string(cfg.methods.run);

for method_idx=1:numel(run_methods)

    method_name = ...
        lower(strtrim(run_methods(method_idx)));

    fprintf('\n');
    fprintf('============================================================\n');
    fprintf('Running method %d/%d: %s\n', ...
        method_idx, ...
        numel(run_methods), ...
        method_name);
    fprintf('============================================================\n');

    switch method_name

        case "eadmm"

            results.eadmm = ...
                run_eadmm_graph_baseline( ...
                    problem, ...
                    cfg);

        case "lp"

            results.lp = ...
                run_lp_baseline( ...
                    problem, ...
                    cfg);

        case "mmdlp"

            results.mmdlp = ...
                run_mmdlp_baseline( ...
                    problem, ...
                    cfg);

        case "random"

            results.random = ...
                run_random_baseline( ...
                    problem, ...
                    cfg);

        case "vector"

            results.vector = ...
                run_vector_baseline( ...
                    problem, ...
                    cfg);

        case "matrix"

            % ----------------------------------------------------
            % Warm-start dependency checks
            % ----------------------------------------------------

            if ...
                    string(cfg.matrix.init_mode)=="lp_best_jcommon" ...
                    && ...
                    ~isfield(results,'lp')

                error( ...
                    ['Matrix init_mode="lp_best_jcommon" requires ', ...
                     'Lp to run before Matrix.']);
            end

            if ...
                    string(cfg.matrix.init_mode)=="eadmm_sdp" ...
                    && ...
                    ~isfield(results,'eadmm')

                error( ...
                    ['Matrix init_mode="eadmm_sdp" requires ', ...
                     'eADMM to run before Matrix.']);
            end

            results.matrix = ...
                run_matrix_multistart( ...
                    problem, ...
                    cfg, ...
                    results);

        otherwise

            error( ...
                'Unknown method: %s.', ...
                method_name);
    end
end

%% ============================================================
% Unified selected-method report
% ============================================================

report = ...
    build_selected_methods_report( ...
        results, ...
        problem, ...
        cfg);

fprintf('\n');
fprintf('============================================================\n');
fprintf('GRAPH OBJECTIVE CONVENTION\n');
fprintf('============================================================\n');
fprintf('All reported J_common values are\n');
fprintf('  J_common(P) = 0.5*<L,P*P''>.\n');
fprintf('This is the original ADMM-GP k-equipartition cut objective.\n');
fprintf('============================================================\n');

print_selected_methods_report( ...
    report, ...
    results, ...
    problem, ...
    cfg);

%% ============================================================
% Save
% ============================================================

if cfg.output.save_results

    result_dir = ...
        fullfile( ...
            project_root, ...
            'results');

    if ~exist(result_dir,'dir')

        mkdir(result_dir);
    end

    result_file = ...
        fullfile( ...
            result_dir, ...
            sprintf( ...
                'graph_%s_N%d_k%d_%s.mat', ...
                char(cfg.graph.family), ...
                cfg.graph.n, ...
                cfg.graph.k, ...
                timestamp));

    save( ...
        result_file, ...
        'cfg', ...
        'data', ...
        'problem', ...
        'results', ...
        'report', ...
        '-v7.3');

    fprintf('\nResults saved to:\n%s\n', ...
        result_file);
end

fprintf('\n');
fprintf('============================================================\n');
fprintf('Graph experiment completed.\n');
fprintf('Log file:\n%s\n',log_file);
fprintf('============================================================\n');

diary off;
clear diary_cleanup;